matriz = [
    [1, "a", 2],
    ["b", 3, 4],
    [6, 5, "c"]
]

print(matriz[0])  # [1, "a", 2]
print(matriz[0][0])  # 1
print(matriz[0][-1])  # 2
print(matriz[-1][-1])  # "c"

matriz_01 = [
    [1, 2, 3],
    ["a", "b", "c"],
    [5, "L", 8]
]

print(matriz_01[1]) # ["a", "b", "c"]
print(matriz_01[1][-1]) # "c"
print(matriz_01[-1][1]) # "L"
